def water_corners(g):
    """The sea and estuary from the bathymetry, plus the big lakes from Natural Earth."""
    sea = g.sample(g.box_blur(g.DEM, 1), g.CORNER_LON, g.CORNER_LAT) < -0.5
    lab, sizes = g.components(sea)
    sea = (lab >= 0) & (sizes[lab] > 3000)          # open sea only: drop the tidal-flat ponds behind the 盐城 coast
    return sea | osmwater.mask(g, osmwater.ne_lakes(LAKE_NAMES))


def ground_cover(g):
    E, R, lon, lat, n1, n2 = g.ELEV_CELL, g.RELIEF_CELL, g.CELL_LON, g.CELL_LAT, g.NOISE, g.NOISE2
    cover = np.full(E.shape, g.GRASS)
    p = np.full(E.shape, 0.01)
    hills = (E > 60) | (R > 25)
    plain = ~hills
    near_water = g.water_cell.copy()
    for _ in range(2):
        near_water = near_water | g.shift(near_water, 1, 0, False) | g.shift(near_water, -1, 0, False) | \
            g.shift(near_water, 0, 1, False) | g.shift(near_water, 0, -1, False)
    coast = near_water & plain & (lon > 119.6) & ((lat > 32.3) | (lon > 121.2))   # 盐城 tidal flats, 崇明
    subei = plain & (lat > 33.0)
    lixiahe = plain & (lat > 32.5) & (lat <= 33.4) & (lon > 119.4)                  # 里下河 lowland
    south = hills & (lat < 31.9)                                                     # 宜溧 / 皖南 forest

    cover[plain & (n1 > 0.55)] = g.THICK                          # rice and wheat
    cover[subei & (n2 > 0.72)] = g.ROUGH                          # dry fields of the Huang-Huai plain
    cover[lixiahe & (n1 > 0.4)] = g.THICK
    cover[coast & (n1 > 0.3)] = g.SAND
    cover[hills & (n2 > 0.6)] = g.ROUGH
    p[plain] = 0.01
    p[lixiahe] = 0.02
    p[hills] = 0.1
    p[south] = 0.2 + 0.3 * (1 - n1[south])
    p[coast] = 0.003
    return cover, hills, p


