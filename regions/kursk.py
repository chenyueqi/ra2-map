def ground_cover(g):
    E, R, lon, lat, n1, n2 = g.ELEV_CELL, g.RELIEF_CELL, g.CELL_LON, g.CELL_LAT, g.NOISE, g.NOISE2
    cover = np.full(E.shape, g.GRASS)
    p = np.full(E.shape, 0.01)
    gullies = R > 14                                          # балки: the gully-cut slopes of the upland
    plain = ~gullies
    north = lat > 52.6                                        # Orel: forest begins
    riparian = g.RIVER_D < 1.3

    cover[plain & (n1 > 0.42)] = g.THICK                      # ripe wheat and rye on the black earth
    cover[plain & (n1 <= 0.42) & (n2 > 0.72)] = g.ROUGH       # trampled, shell-cratered fields
    cover[gullies & (n2 > 0.5)] = g.ROUGH
    p[plain] = 0.008
    p[gullies] = 0.12 + 0.15 * (1 - n1[gullies])               # gully woods (байрачные леса)
    p[riparian] = 0.12
    p[north] = np.maximum(p[north], 0.05 + 0.12 * (1 - n2[north]))
    return cover, gullies, p


