def water_corners(g):
    return osmwater.mask(g, osmwater.ne_lakes(LAKE_NAMES))


def ground_cover(g):
    E, R, lon, lat, n1, n2 = g.ELEV_CELL, g.RELIEF_CELL, g.CELL_LON, g.CELL_LAT, g.NOISE, g.NOISE2
    cover = np.full(E.shape, g.GRASS)
    p = np.full(E.shape, 0.006)
    hills = (E > 80) | (R > 22)
    plain = ~hills
    riparian = (g.RIVER_D < 1.2) & plain

    cover[plain & (n1 > 0.45)] = g.ROUGH                      # bare winter fields, frozen
    cover[plain & (n1 <= 0.45) & (n2 > 0.6)] = g.THICK        # winter wheat
    cover[hills & (n2 > 0.5)] = g.ROUGH
    p[plain] = 0.006
    p[riparian] = 0.06
    p[hills] = 0.08                                           # the Xuzhou hills, 芒砀山, 皇藏峪
    return cover, hills, p


